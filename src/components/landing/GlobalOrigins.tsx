/** Control point of the route arc: lifted off the straight line (always
 *  bowing "up" the map), lift proportional to the distance. */
function routeControl(from: { x: number; y: number }, to: { x: number; y: number }) {
  const dx = to.x - from.x;
  const dy = to.y - from.y;
  const len = Math.hypot(dx, dy) || 1;
  let nx = -dy / len;
  let ny = dx / len;
  if (ny > 0) {
    nx = -nx;
    ny = -ny;
  }
  const lift = Math.min(len * 0.2, 120);
  return { x: (from.x + to.x) / 2 + nx * lift, y: (from.y + to.y) / 2 + ny * lift };
}

/** Route from an origin into Colombo (quadratic arc). */
function routePath(from: { x: number; y: number }, to: { x: number; y: number }) {
  const c = routeControl(from, to);
  return `M${from.x} ${from.y}Q${c.x.toFixed(1)} ${c.y.toFixed(1)} ${to.x} ${to.y}`;
}

/** Phone camera: a viewBox framing one route (origin, Colombo and the arc's
 *  apex) at a 4:3 aspect, at least 440 units wide, kept inside the map. */
const CAM_ASPECT = 4 / 3;
function cameraFor(key: string) {
  const p = ORIGIN_POINTS[key];
  const h = HUB_POINT;
  const c = routeControl(p, h);
  const apex = { x: (p.x + 2 * c.x + h.x) / 4, y: (p.y + 2 * c.y + h.y) / 4 };
  const xs = [p.x, h.x, apex.x];
  const ys = [p.y, h.y, apex.y];
  const pad = 56;
  let x0 = Math.min(...xs) - pad;
  const x1 = Math.max(...xs) + pad;
  let y0 = Math.min(...ys) - pad;
  const y1 = Math.max(...ys) + pad + 20; // room for the hub label
  let w = Math.max(x1 - x0, 440);
  let hgt = y1 - y0;
  if (w / hgt < CAM_ASPECT) w = hgt * CAM_ASPECT;
  else hgt = w / CAM_ASPECT;
  const cx = (x0 + x1) / 2;
  const cy = (y0 + y1) / 2;
  w = Math.min(w, MAP_W);
  hgt = Math.min(hgt, MAP_H);
  x0 = Math.min(Math.max(cx - w / 2, 0), MAP_W - w);
  y0 = Math.min(Math.max(cy - hgt / 2, 0), MAP_H - hgt);
  return { x: x0, y: y0, w, h: hgt };
}

