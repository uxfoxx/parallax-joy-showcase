/** Selected country's silhouette (shared 0–100 box), styled for the dark card. */
const Silhouette = ({ shapeKey, reduced }: { shapeKey: string; reduced: boolean }) => {
  const shape = COUNTRY_SHAPES[shapeKey];
  if (!shape) return null;
  const [mx, my] = shape.marker;
  return (
    <svg viewBox="0 0 100 100" className="w-full h-full" aria-hidden>
      <motion.path
        d={shape.d}
        fill="hsl(var(--accent) / 0.12)"
        stroke="hsl(var(--accent) / 0.55)"
        strokeWidth={0.8}
        strokeLinejoin="round"
        initial={{ opacity: 0, scale: 0.94 }}
        animate={{ opacity: 1, scale: 1 }}
        transition={{ duration: 0.6, ease: EASE }}
        style={{ transformOrigin: "50% 50%" }}
      />
      {!reduced && (
        <motion.path
          d={shape.d}
          fill="none"
          stroke="hsl(var(--accent))"
          strokeWidth={1.2}
          strokeLinejoin="round"
          initial={{ pathLength: 0, opacity: 1 }}
          animate={{ pathLength: 1, opacity: 0 }}
          transition={{ duration: 1.6, ease: EASE }}
        />
      )}
      {!reduced && (
        <motion.circle
          cx={mx}
          cy={my}
          fill="none"
          stroke="hsl(var(--accent))"
          strokeWidth={0.8}
          initial={{ r: 2, opacity: 0.9 }}
          animate={{ r: 11, opacity: 0 }}
          transition={{ duration: 1.8, repeat: Infinity, ease: "easeOut" }}
        />
      )}
      <circle cx={mx} cy={my} r={2.6} fill="hsl(var(--accent))" />
      <circle cx={mx} cy={my} r={1.1} fill="hsl(150 40% 7%)" />
    </svg>
  );
};

